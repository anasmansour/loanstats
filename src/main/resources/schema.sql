CREATE TABLE loans (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_amnt      DECIMAL(10, 2),
    int_rate       DECIMAL(10, 4),
    grade          VARCHAR(10) NOT NULL,
    issue_d        DATE        NOT NULL,
    purpose        VARCHAR(50),
    addr_state     CHAR(2),
    dti            DECIMAL(10, 2),
    fico_range_low INT,
    fico_band      VARCHAR(20)
);
